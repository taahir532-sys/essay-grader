    pdf.rect(0, 0, 210, 35, 'F')
    pdf.set_y(8)
    pdf.set_font("Arial", 'B', 16)
    pdf.set_text_color(255,255,255)
    pdf.cell(0, 10, "Mr Mahomed | Essay Grader Report", ln=True, align='C')
    pdf.set_font("Arial", '', 9)
    pdf.set_text_color(180,180,180)
    pdf.cell(0, 5, "AI Grading + CEFR Level + Fix | beacons.ai/mr_mahomed", ln=True, align='C')
    pdf.ln(20)
    pdf.set_text_color(0,0,0)
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(0, 8, f"Target Level: {target_level} | Date: {datetime.now().strftime('%d %b %Y')}", ln=True)
    pdf.set_font("Arial", '', 9)
    pdf.set_text_color(100,100,100)
    pdf.cell(0, 5, "Graded in 4.8s | 50 essays: 8hrs -> 4.2mins saved", ln=True)
    pdf.ln(5)
    pdf.set_fill_color(239, 246, 255)
    pdf.set_draw_color(59, 130, 246)
    pdf.rect(10, pdf.get_y(), 190, 25, 'DF')
    pdf.set_xy(12, pdf.get_y()+2)
    pdf.set_font("Arial", 'B', 11)
    pdf.set_text_color(30, 64, 175)
    short_result = ai_result[:250].replace('\n',' ')
